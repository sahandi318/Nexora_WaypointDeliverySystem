function interpolate(



  template,



  variables



) {



  if (



    !variables ||



    typeof variables !==



      "object"



  ) {



    return template;



  }







  return template.replace(



    /\*\*\\\\{\*\*([a-zA-Z0-9\\\_]+)\*\*\\\\}\*\*/g,



    (



      match,



      key



    ) => {



      if (



        Object.prototype



          .hasOwnProperty.call(



            variables,



            key



          )



      ) {



        return String(



          variables[key]



        );



      }







      return match;



    }



  );



}







export function getStaticTranslation({



  language,



  key,



  fallback,



  variables,



}) {



  const selectedLanguage =



    STATIC_TRANSLATIONS[



      language



    ] ||



    STATIC_TRANSLATIONS.en;







  const englishText =



    STATIC_TRANSLATIONS.en[



      key



    ];







  const translatedText =



    selectedLanguage[



      key



    ];







  const resolvedText =



    translatedText ||



    englishText ||



    fallback ||



    key;







  return interpolate(



    resolvedText,



    variables



  );



}







export function hasStaticTranslation(



  key



) {



  return Boolean(



    STATIC_TRANSLATIONS.en[



      key



    ]



  );



}







